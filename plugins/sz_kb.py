def _area_hit(text: str) -> list[str]:
    """按在句子里出现的先后排 —— 他先问哪个就先说哪个。

    2026-11-07：「龙华租房多少钱，到南山上班远不远」原来会先给南山（字典顺序），
    但他是住龙华、去南山上班，重点在龙华。
    """
    found = [(text.find(k), k) for k in AREAS if k in text]
    found.sort()
    return [k for _pos, k in found]


