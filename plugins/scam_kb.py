def _hit_case(text: str) -> list[dict]:
    """core 命中 1 个就判；weak 要凑 2 个（防误报）。

    2026-11-07：原来是一层 script 精确匹配，漏得很厉害 ——
    主人说「快递丢了」不会命中「快递丢失」，说「下个app」不命中「下载这个APP」。
    拆成 core（高危词，1个即判）+ weak（泛词，2个才算）。
    """
    t = str(text or "")
    out: list[dict] = []
    for c in CASES:
        core_hits = [k for k in (c.get("core") or []) if k and k in t]
        weak_hits = [k for k in (c.get("weak") or []) if k and k in t]
        if not core_hits and len(weak_hits) < 2:
            continue
        out.append({
            "name": c["name"], "gate": c["gate"],
            "score": len(core_hits) * 3 + len(weak_hits),
            "hit": core_hits + weak_hits,
            "red": c["red"], "tell": c["tell"],
        })
    out.sort(key=lambda x: -x["score"])
    return out


def detect(text: str) -> list[dict]:
    """这句话像不像在说一件可能有坑的事。空列表=没看出来。"""
    t = str(text or "").strip()
    if len(t) < 5:
        return []
    if not _TRIGGER.search(t):
        return []
    return _hit_case(t)


def line(text: str) -> str:
    """命中时给 prompt 的一段。没命中返回空串（不占 token）。

    只给要点，不给整段知识 —— 她要的是"认出这是哪类坑"，不是背课文。
    """
    hits = detect(text)
    if not hits:
        return ""
    top = hits[:2]
    parts = ["【这事有坑，你先警觉】"]
    for h in top:
        parts.append(f"· 像「{h['name']}」（{h['gate']}门）")
        if h.get("red"):
            parts.append("  信号：" + "／".join(h["red"][:2]))
        if h.get("tell"):
            parts.append("  " + h["tell"])
    parts.append("回他时别绕弯子：直接说哪儿不对、让他别转钱、让他先核实。"
                 "如果他自己就是冲着这个去的，也别讲大道理，一句话点破就行。")
    return "\n".join(parts)


