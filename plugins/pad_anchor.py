"""PAD 坐标：用中科院量表锚点算，不再手调系数。

2026-11-07 校准。

之前 memory_mood.pad_now() 里的权重（乐×1.0 − 哀×0.9 …）是我拍的，没有出处。
现在改成：把 7 维情绪映射到中科院 PAD 量表的 14 个情绪锚点，
再按强度做凸组合 —— 每个坐标都能追到论文里的某个锚点，而且凸组合天然不越界。

锚点来源：Wang et al. 2023, JAMDSM 17(5), Table 2（原值 ±4 已归一化到 −1…1）。
数值取自 npm 包 dsh-emotion-memory v0.1.4 的 lib/model.js（作者照论文抄的）。

    喜悦 (0.693, 0.302, 0.355)   乐观 (0.620, 0.263, 0.438)
    放松 (0.547,-0.165, 0.263)   惊讶 (0.430, 0.427, 0.055)
    温和 (0.393,-0.198, 0.095)   依赖 (0.098,-0.203,-0.370)
    无聊 (-0.133,-0.313,-0.210)  悲伤 (-0.223, 0.043,-0.175)
    恐惧 (-0.233, 0.325,-0.160)  焦虑 (-0.237, 0.080,-0.158)
    轻蔑 (-0.395, 0.080, 0.255)  厌恶 (-0.450, 0.100, 0.168)
    怨恨 (-0.495, 0.275, 0.150)  敌意 (-0.520, 0.250, 0.280)
"""
from __future__ import annotations

# 14 个锚点（P 愉悦 / A 唤醒 / D 掌控）
ANCHORS: dict[str, tuple[float, float, float]] = {
    "喜悦": (0.693, 0.302, 0.355),
    "乐观": (0.620, 0.263, 0.438),
    "放松": (0.547, -0.165, 0.263),
    "惊讶": (0.430, 0.427, 0.055),
    "温和": (0.393, -0.198, 0.095),
    "依赖": (0.098, -0.203, -0.370),
    "无聊": (-0.133, -0.313, -0.210),
    "悲伤": (-0.223, 0.043, -0.175),
    "恐惧": (-0.233, 0.325, -0.160),
    "焦虑": (-0.237, 0.080, -0.158),
    "轻蔑": (-0.395, 0.080, 0.255),
    "厌恶": (-0.450, 0.100, 0.168),
    "怨恨": (-0.495, 0.275, 0.150),
    "敌意": (-0.520, 0.250, 0.280),
}

# 基线：没有情绪时的落点（跟包里的默认一致）
BASELINE = (0.15, -0.10, 0.00)

# 三轴的可信度权重。
# 依据：中文简化版 PAD 量表的内部一致性（李晓明、傅小兰、邓国峰 2008，
# 中国心理卫生杂志 22(5):327-329，1000 名北京本科生）：
#     P 愉悦度 α = 0.85   「内部一致性较好」
#     A 激活度 α = 0.58   「内部一致性略低」   ← 心理学通常要求 ≥0.70
#     D 优势度 α = 0.72   「内部一致性较好」
# 以 P 为基准折算：A 只值 68% 的可信度，D 值 85%。
# 所以 A 不能在距离/相似度里和 P 等权 —— 否则一个测不准的轴会主导判断。
#
# 2026-11-07 二次下调（依据：PAIR，UIUC/KAIST，1093 次会话实证，
# 把 AI 推断的 PAD 和用户自评 SAM 对拍）：
#     Valence   r = 0.681   → 基准
#     Dominance r = 0.538
#     Arousal   r = 0.236   ← 只有 P 的三分之一
# 按 r 比值 A 该是 0.35，按 α 比值是 0.68。取中间偏保守 → 0.45。
# 两个独立来源（中文量表 α / 英文实测 r）都指向"唤醒度测不准"，这条结论很硬。
RELIABILITY = {"P": 1.00, "A": 0.45, "D": 0.85}

# 我们 7 维情绪 → 锚点的混合权重。
# 每一行加起来 = 1.0，这样"某维 100 分"就等于那一行锚点的加权中心。
_TO_ANCHOR: dict[str, dict[str, float]] = {
    # 开心 ≈ 喜悦（几乎一一对应）
    "开心": {"喜悦": 1.0},
    # 害羞 = 高兴但收敛、还带着依赖感（温和 + 依赖）
    "害羞": {"温和": 0.60, "依赖": 0.40},
    # 情欲 = 愉悦 + 兴奋 + 有点主动（喜悦 + 乐观 + 温和）
    "情欲": {"喜悦": 0.50, "乐观": 0.30, "温和": 0.20},
    # 烦 = 说不上恨，主要是嫌弃和没劲
    "烦": {"厌恶": 0.40, "轻蔑": 0.35, "无聊": 0.25},
    # 怒 = 冲着人去的（敌意 + 怨恨）
    "怒": {"敌意": 0.55, "怨恨": 0.45},
    # 丧 = 低落、提不起劲
    "丧": {"悲伤": 0.65, "无聊": 0.35},
    # 累 ≠ 负情绪：低唤醒为主（这是"没力气"而不是"难过"）
    # 2026-11-07 调：原来 55/45 的加权中心离「温和」更近，读起来像心情不错；
    # 改成 75/25 之后落到「无聊」附近，才对得上"蔫蔫提不起劲"
    "累": {"无聊": 0.75, "放松": 0.25},
    # 害怕 = 恐惧为主，带焦虑
    "害怕": {"恐惧": 0.70, "焦虑": 0.30},
}


def _unit(x: float) -> float:
    return max(0.0, min(1.0, x / 100.0))


def pad_from_emotions(emo: dict[str, float]) -> dict:
    """7 维情绪（0~100）→ PAD（−1…1）。空输入返回基线。"""
    P = A = D = 0.0
    total = 0.0
    for name, mapping in _TO_ANCHOR.items():
        v = _unit(float((emo or {}).get(name) or 0.0))
        if v <= 0.02:                     # 基本没起来，别拖低均值
            continue
        for anchor, w in mapping.items():
            a = ANCHORS.get(anchor)
            if not a:
                continue
            k = v * w
            P += k * a[0]
            A += k * a[1]
            D += k * a[2]
            total += k
    if total < 1e-6:
        return {"P": BASELINE[0], "A": BASELINE[1], "D": BASELINE[2]}
    # 凸组合：落在锚点凸包内，天然不会越界
    return {"P": round(P / total, 3),
            "A": round(A / total, 3),
            "D": round(D / total, 3)}


def nearest_anchor(pad: dict) -> str:
    """这个 PAD 坐标最接近哪个锚点（给"现在像什么情绪"一个学术说法）。"""
    P = float(pad.get("P") or 0)
    A = float(pad.get("A") or 0)
    D = float(pad.get("D") or 0)
    wP = RELIABILITY["P"]
    wA = RELIABILITY["A"]
    wD = RELIABILITY["D"]
    best, bestd = "", 1e9
    for name, (p, a, d) in ANCHORS.items():
        # 加权距离：激活度测不准，就少让它说话
        dist = (wP * (P - p) ** 2) + (wA * (A - a) ** 2) + (wD * (D - d) ** 2)
        if dist < bestd:
            best, bestd = name, dist
    return best
